"""Build configuration for Advanced Timegrapher native C++ extensions."""

from __future__ import annotations

import hashlib
import os
import sys
from pathlib import Path

from pybind11.setup_helpers import Pybind11Extension, build_ext
from setuptools import setup

ROOT = Path(__file__).resolve().parent
cpp_path = ROOT / "src" / "adv_tg" / "dsp" / "native_dsp.cpp"
hash_header_path = ROOT / "src" / "adv_tg" / "dsp" / "native_dsp_source_hash.h"

# Generate source hash header before building extension
if cpp_path.is_file():
    sha = hashlib.sha256(cpp_path.read_bytes()).hexdigest()
    header_content = (
        "/* Auto-generated by setup.py; do not edit. */\n"
        "#pragma once\n"
        f'#define NATIVE_DSP_SOURCE_SHA256 "{sha}"\n'
    )
    if (
        not hash_header_path.is_file()
        or hash_header_path.read_text(encoding="utf-8") != header_content
    ):
        hash_header_path.write_text(header_content, encoding="utf-8")

skip_native = os.environ.get("ADV_TG_SKIP_NATIVE", "").strip().lower() in ("1", "true", "yes")
ext_modules = []

if not skip_native and cpp_path.is_file():
    extra_compile_args = []
    extra_link_args = []

    if sys.platform == "win32":
        extra_compile_args = ["/O2", "/fp:fast", "/std:c++17"]
    else:
        # -ffast-math for speed, but -fno-finite-math-only keeps NaN/inf meaningful; every
        # division in native_dsp.cpp is noise gated (kGate) so none can blow up.
        extra_compile_args = ["-O3", "-ffast-math", "-fno-finite-math-only", "-std=c++17"]

    ext_modules = [
        Pybind11Extension(
            "adv_tg.dsp.adv_tg_dsp_native",
            [str(cpp_path.relative_to(ROOT))],
            extra_compile_args=extra_compile_args,
            extra_link_args=extra_link_args,
            optional=True,
        ),
    ]

setup(
    ext_modules=ext_modules,
    cmdclass={"build_ext": build_ext},
)
